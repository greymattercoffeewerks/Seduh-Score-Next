// Generates supabase/tests/060b_phone_fixture_cases.sql (a pgTAP test) from tests/fixtures/phone-cases.json,
// so the database is checked against the SAME cases the client tests use (Handoffs and Specs/
// PHONE-CHECKER-DESIGN.md section 5). The cases are embedded in the generated test because `supabase test db`
// runs pg_prove in a container that sees only supabase/tests, so a test cannot `\i` a file outside it, and a
// fixture-only .sql file inside it would be run as a test. The JSON is the source; never edit the SQL by hand.
// src/core/phone.test.js fails when the committed file is stale.
//
//   npm run fixtures:phone
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const FIXTURE_JSON = resolve(ROOT, 'tests/fixtures/phone-cases.json');
export const FIXTURE_SQL = resolve(ROOT, 'supabase/tests/060b_phone_fixture_cases.sql');

const literal = (value) => (value === null ? 'null' : `'${String(value).replaceAll("'", "''")}'`);

const ORG = "'00000000-0000-0000-0000-0000000b60a0'";
const ENTRY = "'00000000-0000-0000-0000-0000000b60f1'";
const PERSON = "'00000000-0000-0000-0000-0000000b60d1'";
const UPDATE_CALL = `update_roster_entry(${ORG}, ${ENTRY}, 'Fixture Person', p, null, null, null)`;

// Pure. The pgTAP test text for a parsed fixture. Column `db` says what the database must do with `input`:
// 'canonical' (store unchanged), 'refuse' (answer phone_invalid), 'skip' (not a database case).
export function renderPhoneCasesSql(fixture) {
  const rows = fixture.cases.map(
    (c) => `  (${[c.id, c.input, c.country, c.expect, c.error, c.db].map(literal).join(', ')})`,
  );
  return [
    '-- GENERATED by tools/generate-phone-fixture-sql.mjs from tests/fixtures/phone-cases.json.',
    '-- Do not edit by hand: run `npm run fixtures:phone`. A vitest test (src/core/phone.test.js) fails when this is stale.',
    '-- T-ID.A3: the database against the shared phone cases. Every expected value passes app.is_e164 and',
    '-- update_roster_entry stores it unchanged (the client output, canonical); every case marked refuse is refused with hint phone_invalid and changes',
    '-- nothing. The database never interprets a number (owner decision 4), so a refuse case is refused even when the',
    "-- client would have turned it into a valid number. Fixture ids use the 'b60' block.",
    'begin;',
    'select no_plan();',
    '',
    'create temp table phone_cases (',
    '  id text primary key,',
    '  input text not null,',
    '  country text,',
    '  expect text,',
    '  error text,',
    "  db text not null check (db in ('canonical', 'refuse', 'skip'))",
    ');',
    'insert into phone_cases (id, input, country, expect, error, db) values',
    `${rows.join(',\n')};`,
    'grant select on phone_cases to authenticated;',
    '',
    "insert into auth.users (id, email) values ('00000000-0000-0000-0000-00000000b060', 'organiser@t060b.seduh-next');",
    `insert into orgs (id, name, slug) values (${ORG}, 'T060b Org', 't060b-org');`,
    `insert into org_members (org_id, user_id, role) values (${ORG}, '00000000-0000-0000-0000-00000000b060', 'organiser');`,
    `insert into events (id, org_id, format, name) values ('00000000-0000-0000-0000-0000000b60e1', ${ORG}, 'cup_taster', 'T060b Event');`,
    `insert into people (id, org_id, display_name, phone) values (${PERSON}, ${ORG}, 'Fixture Person', '+6738123456');`,
    `insert into event_entries (id, event_id, person_id, display_name) values (${ENTRY}, '00000000-0000-0000-0000-0000000b60e1', ${PERSON}, 'Fixture Person');`,
    '',
    '-- The fixture is neither empty nor lopsided (a broken generator must not pass by checking nothing).',
    "select cmp_ok((select count(*) from phone_cases where db = 'canonical'), '>=', 2::bigint, 'fixture: at least two canonical cases');",
    "select cmp_ok((select count(*) from phone_cases where db = 'refuse'), '>=', 30::bigint, 'fixture: at least thirty refuse cases');",
    "select ok((select bool_and(input = expect) from phone_cases where db = 'canonical'), 'fixture: a canonical case is its own expected value');",
    '',
    '-- app.is_e164 accepts every canonical case, and does not accept the raw input of any refuse case.',
    "select ok(app.is_e164(expect), 'is_e164 accepts the expected value of ' || id) from phone_cases where expect is not null and db <> 'skip' order by id;",
    "select ok(not app.is_e164(input), 'is_e164 rejects the raw input of ' || id) from phone_cases where db = 'refuse' order by id;",
    '',
    '-- What update_roster_entry does, as a signed-in member of the fixture organisation.',
    'create function pg_temp.stored_after(p text) returns text language plpgsql as $f$',
    'begin',
    `  perform ${UPDATE_CALL};`,
    `  return (select phone from people where id = ${PERSON});`,
    'end $f$;',
    '',
    'create function pg_temp.hint_of(p text) returns text language plpgsql as $f$',
    'declare h text;',
    'begin',
    `  perform ${UPDATE_CALL};`,
    "  return 'no error';",
    'exception when others then',
    '  get stacked diagnostics h = pg_exception_hint;',
    '  return h;',
    'end $f$;',
    '',
    'set local role authenticated;',
    "set local request.jwt.claim.sub = '00000000-0000-0000-0000-00000000b060';",
    '',
    "select is(pg_temp.stored_after(expect), expect, 'update_roster_entry stores the expected value of ' || id || ' unchanged')",
    "from phone_cases where expect is not null and db <> 'skip' order by id;",
    '',
    "select is(pg_temp.hint_of(input), 'phone_invalid', 'update_roster_entry refuses ' || id)",
    "from phone_cases where db = 'refuse' order by id;",
    '',
    '-- The refused calls changed nothing: the person still holds the last canonical value stored above.',
    'select is(',
    `  (select phone from people where id = ${PERSON}),`,
    "  (select expect from phone_cases where expect is not null and db <> 'skip' order by id desc limit 1),",
    "  'refused inputs changed nothing');",
    '',
    'select * from finish();',
    'rollback;',
    '',
  ].join('\n');
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const fixture = JSON.parse(readFileSync(FIXTURE_JSON, 'utf8'));
  mkdirSync(dirname(FIXTURE_SQL), { recursive: true });
  writeFileSync(FIXTURE_SQL, renderPhoneCasesSql(fixture));
  console.log(`wrote ${FIXTURE_SQL} (${fixture.cases.length} cases)`);
}
