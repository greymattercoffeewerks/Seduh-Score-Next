// Generates supabase/tests/fixtures/phone_cases.sql from tests/fixtures/phone-cases.json, so the
// database tests read the SAME cases the client tests do without pgTAP having to read JSON
// (Handoffs and Specs/PHONE-CHECKER-DESIGN.md section 5). The JSON is the source; never edit the
// SQL by hand. phone.fixture.test.js fails when the committed file is stale.
//
//   npm run fixtures:phone
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const FIXTURE_JSON = resolve(ROOT, 'tests/fixtures/phone-cases.json');
export const FIXTURE_SQL = resolve(ROOT, 'supabase/tests/fixtures/phone_cases.sql');

const literal = (value) => (value === null ? 'null' : `'${String(value).replaceAll("'", "''")}'`);

// Pure. The SQL text for a parsed fixture. A temp table, so a test file can `\i` it inside its own
// transaction and nothing outlives the session. Column `db` says what the database must do with
// `input`: 'canonical' (store unchanged), 'refuse' (answer phone_invalid), 'skip' (not a DB case).
export function renderPhoneCasesSql(fixture) {
  const rows = fixture.cases.map(
    (c) => `  (${[c.id, c.input, c.country, c.expect, c.error, c.db].map(literal).join(', ')})`,
  );
  return [
    '-- GENERATED by tools/generate-phone-fixture-sql.mjs from tests/fixtures/phone-cases.json.',
    '-- Do not edit by hand: run `npm run fixtures:phone`. A vitest test fails when this is stale.',
    'create temp table phone_cases (',
    '  id text primary key,',
    '  input text not null,',
    '  country text,',
    '  expect text,',
    '  error text,',
    "  db text not null check (db in ('canonical', 'refuse', 'skip'))",
    ');',
    'insert into phone_cases (id, input, country, expect, error, db) values',
    `${rows.join(',\n')};`,
    '',
  ].join('\n');
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const fixture = JSON.parse(readFileSync(FIXTURE_JSON, 'utf8'));
  mkdirSync(dirname(FIXTURE_SQL), { recursive: true });
  writeFileSync(FIXTURE_SQL, renderPhoneCasesSql(fixture));
  console.log(`wrote ${FIXTURE_SQL} (${fixture.cases.length} cases)`);
}
