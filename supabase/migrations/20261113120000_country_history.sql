-- Seduh Score Next · T-CTY.1: Seduh ID country pages, the database half
--
-- Why: a public record per country of the teams it sent to the Barista Team Championship (BTC), filled in from the
-- competition organiser's own historical results (Handoffs and Specs/SEDUH-ID-COUNTRY-PAGES-SPEC-DRAFT.md sections 3, 6;
-- first source: the ASEAN Coffee Federation's 2023 to 2026 scoreboards). Nobody claims a country page, so there is no
-- login and no person: only team names, countries, and how far each team went.
--
-- What this adds:
--   * app.historical_results: one row per team per championship edition, as the organiser supplied it. Platform data,
--     in the `app` schema with RLS on, NO policy, an ACL naming only the owner and every API-role privilege revoked
--     (the pattern of app.seduh_identities, 20261030120000). It is NOT a tenant table: it has no org_id and belongs
--     to no organisation (the supplier is often not on Seduh Score), so the cross-organisation table matrix (040) and
--     the tenant-parent guards (033, 042), which cover `public` only, do not apply and need no entry or exemption.
--     Written only by the owner (the import script's generated SQL); there is no API write path at all.
--       permission_ref is NOT NULL and non-blank: a row cannot exist without a record of who allowed it to be published
--       (spec CP1). placement is 1 to 4 and only where the organiser published a number, and it must agree with the
--       stage (1 = champion, 2 = final, 3 or 4 = semi_final). listed is the soft unpublish: false hides the row from
--       both doors and keeps it (a removal is never a delete, spec 6.3).
--   * app.historical_round_scores: one row per team per round (the organiser publishes round scores), keyed to its
--     results row. r1 and r2 are both present or both null, and when present they add up to score.
--   * app.historical_stage_order(text): the order of the stage vocabulary. The stage is stored as a word; its rank is
--     never stored, only computed (the "`correct` is a count, never a column" rule).
--   * public.public_country_record(p_country_code text) and public.public_country_index(): the two anonymous doors.
--     SECURITY DEFINER, STABLE, search_path pinned to the empty string, executable by anon and authenticated only.
--     They return LISTED rows, each labelled provenance 'organiser_archive', and no id, phone, organisation, event,
--     source_ref, permission_ref or supply date. An unknown, malformed, empty or NULL code gets an empty record of the
--     same shape as a real one, never an error. Every count, "best finish" and win/loss figure is derived inside the
--     function; nothing of the kind is stored.
--
-- LIVE BTC EVENTS ARE NOT READ HERE. is_shadow and the payload country do not exist yet (MARCH-2027-BOARD-PLAN P1), so
-- public_country_record has a clearly marked empty branch (v_live) where live events with provenance 'seduh_score'
-- will be added by a later migration. Shadow-run results must never appear.
--
-- Naming: neither door's name nor body uses the words the platform-tables guard (050) matches on (admin, platform),
-- because these are public doors, not console functions. 050 pins the table list, which gains the two tables below.
-- 041 (the cross-organisation RPC matrix) only sees functions that take a uuid; these take text or nothing, so it
-- needs no entry. 078_country_history.sql pins the doors' shape and privileges instead.
--
-- Data: nothing is inserted here. Loading is owner SQL generated by scripts/country-history (CONVENTIONS.md runbook).
-- Once loaded, ANYONE holding the public anon key can call the doors, with or without a page: loading is publishing.
--
-- ROLLBACK LOSES DATA once the tables hold rows (the loaded results live only here and in the owner's source files).
--
-- rollback:
--   drop function if exists public.public_country_index();
--   drop function if exists public.public_country_record(text);
--   drop table if exists app.historical_round_scores;
--   drop table if exists app.historical_results;
--   drop function if exists app.historical_stage_order(text);

create function app.historical_stage_order(p_stage text)
returns smallint
language sql
immutable
set search_path = ''
as $$
  select case p_stage
    when 'champion'       then 6
    when 'final'          then 5
    when 'semi_final'     then 4
    when 'quarter_final'  then 3
    when 'preliminary'    then 2
    when 'entered'        then 1
  end::smallint
$$;
revoke all on function app.historical_stage_order(text) from public, anon, authenticated, service_role;

create table app.historical_results (
  id                uuid primary key default gen_random_uuid(),
  competition       text not null,
  competition_name  text not null,
  edition_year      smallint not null,
  host_city         text,
  host_country_code text,
  team_name         text not null,
  country_code      text not null,
  stage_reached     text not null,
  placement         smallint,
  score_note        text,
  source_ref        text not null,
  supplied_by       text not null,
  supplied_on       date not null,
  permission_ref    text not null,
  listed            boolean not null default true,
  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now(),
  constraint historical_results_natural_key
    unique (competition, edition_year, country_code, team_name),
  -- BTC only for now (spec CP5); a second competition is a new migration, on purpose.
  constraint historical_results_competition_vocab
    check (competition in ('btc')),
  constraint historical_results_competition_name_length
    check (char_length(competition_name) between 1 and 120),
  -- A fixed lower bound and a far upper one: a CHECK cannot use now() safely (a restore would re-test it). The import
  -- script refuses a year in the future.
  constraint historical_results_edition_year_range
    check (edition_year between 2000 and 2100),
  constraint historical_results_host_city_length
    check (host_city is null or char_length(host_city) between 1 and 80),
  constraint historical_results_host_country_shape
    check (host_country_code is null or host_country_code ~ '^[A-Z]{2}$'),
  constraint historical_results_team_name_length
    check (char_length(team_name) between 1 and 120),
  constraint historical_results_country_shape
    check (country_code ~ '^[A-Z]{2}$'),
  constraint historical_results_stage_vocab
    check (stage_reached in ('champion', 'final', 'semi_final', 'quarter_final', 'preliminary', 'entered')),
  -- A published number is 1 to 4 and must agree with the stage: 1 won the final, 2 lost it, 3 and 4 are the
  -- semi-finalists (so this one check is also the 1-to-4 range).
  constraint historical_results_placement_matches_stage
    check (placement is null
           or (placement = 1 and stage_reached = 'champion')
           or (placement = 2 and stage_reached = 'final')
           or (placement in (3, 4) and stage_reached = 'semi_final')),
  constraint historical_results_score_note_length
    check (score_note is null or char_length(score_note) between 1 and 500),
  constraint historical_results_source_ref_length
    check (char_length(btrim(source_ref)) between 1 and 200),
  constraint historical_results_supplied_by_length
    check (char_length(btrim(supplied_by)) between 1 and 120),
  -- Who gave written permission to publish, and when (spec CP1): never NULL, never blank.
  constraint historical_results_permission_ref_present
    check (char_length(btrim(permission_ref)) between 1 and 300)
);

-- The doors filter on country_code and listed.
create index historical_results_country_listed_idx
  on app.historical_results (country_code) where listed;

create trigger trg_historical_results_set_updated_at
  before update on app.historical_results
  for each row execute function app.set_updated_at();

alter table app.historical_results enable row level security;
revoke all on app.historical_results from public, anon, authenticated, service_role;

create table app.historical_round_scores (
  id                 uuid primary key default gen_random_uuid(),
  result_id          uuid not null references app.historical_results (id) on delete cascade,
  round              text not null,
  r1                 smallint,
  r2                 smallint,
  score              smallint not null,
  opponent_team_name text,
  opponent_score     smallint,
  constraint historical_round_scores_one_per_round
    unique (result_id, round),
  constraint historical_round_scores_round_vocab
    check (round in ('preliminary', 'quarter_final', 'semi_final', 'final_champion', 'final_runner_up')),
  constraint historical_round_scores_nonnegative
    check (score >= 0 and coalesce(r1, 0) >= 0 and coalesce(r2, 0) >= 0 and coalesce(opponent_score, 0) >= 0),
  -- Two summed rounds are both there or both absent, and then add up (the organiser prints the total).
  constraint historical_round_scores_r1_r2_pair
    check ((r1 is null) = (r2 is null)),
  constraint historical_round_scores_r1_r2_total
    check (r1 is null or r1 + r2 = score),
  -- A pairing is a name and a score together, or neither.
  constraint historical_round_scores_opponent_pair
    check ((opponent_team_name is null) = (opponent_score is null)),
  constraint historical_round_scores_opponent_name_length
    check (opponent_team_name is null or char_length(opponent_team_name) between 1 and 120)
);

alter table app.historical_round_scores enable row level security;
revoke all on app.historical_round_scores from public, anon, authenticated, service_role;

-- ---------------------------------------------------------------------------------------------------------------
-- public.public_country_record: one country's record. Always returns the same keys.
-- ---------------------------------------------------------------------------------------------------------------
create function public.public_country_record(p_country_code text)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_code        text := upper(btrim(coalesce(p_country_code, '')));
  v_champs      jsonb;
  v_teams       jsonb;
  v_best        jsonb;
  v_live        jsonb := '[]'::jsonb;
  v_n_champs    integer;
  v_n_entries   integer;
  v_n_teams     integer;
  v_won         integer;
  v_lost        integer;
begin
  -- A code that is not two letters matches nothing; it is not echoed back (no oracle, no reflection).
  if v_code !~ '^[A-Z]{2}$' then
    v_code := null;
  end if;

  -- Stats, derived on read: nothing here is stored.
  select count(distinct h.competition || ':' || h.edition_year), count(*), count(distinct h.team_name)
    into v_n_champs, v_n_entries, v_n_teams
    from app.historical_results h
   where h.listed and h.country_code = v_code;

  -- Matches with a known opponent: a round whose pairing the organiser published. Level scores count for neither.
  select count(*) filter (where s.score > s.opponent_score),
         count(*) filter (where s.score < s.opponent_score)
    into v_won, v_lost
    from app.historical_results h
    join app.historical_round_scores s on s.result_id = h.id
   where h.listed and h.country_code = v_code and s.opponent_team_name is not null
     -- an opponent that has been unlisted is not shown, and its match is not counted either (a removal is complete)
     and exists (select 1 from app.historical_results o where o.listed and o.competition = h.competition and o.edition_year = h.edition_year and o.team_name = s.opponent_team_name);

  -- Best finish: deepest stage, then the best published placement, then the most recent year.
  select jsonb_build_object(
           'team_name', h.team_name, 'competition', h.competition, 'edition_year', h.edition_year,
           'stage_reached', h.stage_reached, 'placement', h.placement)
    into v_best
    from app.historical_results h
   where h.listed and h.country_code = v_code
   order by app.historical_stage_order(h.stage_reached) desc, h.placement nulls last,
            h.edition_year desc, h.team_name
   limit 1;

  -- By championship, newest first; teams furthest first; rounds in playing order.
  select coalesce(jsonb_agg(c.j order by c.edition_year desc, c.competition), '[]'::jsonb)
    into v_champs
    from (
      select h.competition, h.edition_year,
             jsonb_build_object(
               'competition', h.competition,
               'competition_name', min(h.competition_name),
               'edition_year', h.edition_year,
               'host_city', min(h.host_city),
               'host_country_code', min(h.host_country_code),
               'supplied_by', min(h.supplied_by),
               'provenance', 'organiser_archive',
               'teams', jsonb_agg(
                 jsonb_build_object(
                   'team_name', h.team_name,
                   'stage_reached', h.stage_reached,
                   'placement', h.placement,
                   'score_note', h.score_note,
                   'provenance', 'organiser_archive',
                   'rounds', coalesce((
                     select jsonb_agg(
                              jsonb_build_object(
                                'round', s.round, 'r1', s.r1, 'r2', s.r2, 'score', s.score,
                                'opponent_team_name', case when exists (select 1 from app.historical_results o where o.listed and o.competition = h.competition and o.edition_year = h.edition_year and o.team_name = s.opponent_team_name) then s.opponent_team_name end,
                                'opponent_score', case when exists (select 1 from app.historical_results o where o.listed and o.competition = h.competition and o.edition_year = h.edition_year and o.team_name = s.opponent_team_name) then s.opponent_score end)
                              order by case s.round
                                         when 'preliminary' then 1 when 'quarter_final' then 2
                                         when 'semi_final' then 3 when 'final_champion' then 4
                                         else 5 end)
                       from app.historical_round_scores s
                      where s.result_id = h.id), '[]'::jsonb))
                 order by app.historical_stage_order(h.stage_reached) desc, h.placement nulls last, h.team_name)
             ) as j
        from app.historical_results h
       where h.listed and h.country_code = v_code
       group by h.competition, h.edition_year
    ) c;

  -- SEAM: live BTC events (provenance 'seduh_score'). A later migration fills v_live with the championships of
  -- published, non-test, non-shadow BTC events in which every team has a country_code, in the SAME shape as above
  -- (competition, edition_year, teams with stage_reached and rounds), and adds them to the teams summary below.
  -- It does not exist yet: is_shadow and the published payload's country are not built. Until then this stays empty.
  v_live := '[]'::jsonb;

  -- Teams, across the years: a team is the same team only by the name the owner loaded (owner rule, 2026-11-13).
  select coalesce(jsonb_agg(t.j order by t.best_order desc, t.team_name), '[]'::jsonb)
    into v_teams
    from (
      select h.team_name,
             max(app.historical_stage_order(h.stage_reached)) as best_order,
             jsonb_build_object(
               'team_name', h.team_name,
               'years', jsonb_agg(h.edition_year order by h.edition_year),
               'best_stage', (array_agg(h.stage_reached
                                order by app.historical_stage_order(h.stage_reached) desc, h.placement nulls last))[1],
               'best_placement', (array_agg(h.placement
                                order by app.historical_stage_order(h.stage_reached) desc, h.placement nulls last))[1],
               'provenance', 'organiser_archive') as j
        from app.historical_results h
       where h.listed and h.country_code = v_code
       group by h.team_name
    ) t;

  return jsonb_build_object(
    'country_code', v_code,
    'has_record', (jsonb_array_length(v_champs) + jsonb_array_length(v_live)) > 0,
    'stats', jsonb_build_object(
      'championships', v_n_champs,
      'entries', v_n_entries,
      'teams', v_n_teams,
      'matches_won', coalesce(v_won, 0),
      'matches_lost', coalesce(v_lost, 0),
      'best_finish', v_best),
    'championships', v_champs || v_live,
    'teams', v_teams);
end;
$$;

revoke all on function public.public_country_record(text) from public, anon, authenticated, service_role;
grant execute on function public.public_country_record(text) to anon, authenticated;

-- ---------------------------------------------------------------------------------------------------------------
-- public.public_country_index: every country with at least one listed row, and its counts (for the hub).
-- ---------------------------------------------------------------------------------------------------------------
create function public.public_country_index()
returns jsonb
language sql
stable
security definer
set search_path = ''
as $$
  select jsonb_build_object(
    'countries',
    coalesce(jsonb_agg(
      jsonb_build_object(
        'country_code', c.country_code,
        'championships', c.championships,
        'entries', c.entries,
        'teams', c.teams,
        'provenance', 'organiser_archive')
      order by c.country_code), '[]'::jsonb))
  from (
    select h.country_code,
           count(distinct h.competition || ':' || h.edition_year) as championships,
           count(*) as entries,
           count(distinct h.team_name) as teams
      from app.historical_results h
     where h.listed
     group by h.country_code
  ) c
$$;

revoke all on function public.public_country_index() from public, anon, authenticated, service_role;
grant execute on function public.public_country_index() to anon, authenticated;
